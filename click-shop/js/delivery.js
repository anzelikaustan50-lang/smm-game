  function rad(x) { return x * Math.PI / 180; }
  function km(a, b) {
    var dLat = rad(b[2] - a[2]), dLon = rad(b[3] - a[3]);
    var h = Math.sin(dLat / 2) * Math.sin(dLat / 2) + Math.cos(rad(a[2])) * Math.cos(rad(b[2])) * Math.sin(dLon / 2) * Math.sin(dLon / 2);
    return 6371 * 2 * Math.atan2(Math.sqrt(h), Math.sqrt(1 - h)) * 1.18; // 1.18: дорога длиннее прямой
  }
